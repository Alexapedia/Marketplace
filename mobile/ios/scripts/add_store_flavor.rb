#!/usr/bin/env ruby
# Adds (or updates) an iOS flavor for one store:
#   ruby ios/scripts/add_store_flavor.rb <store> <bundle id> "<Display Name>" [AppIcon set]
# Creates Flutter/stores/<store>.xcconfig, the Debug-/Release-/Profile-<store>
# build configurations, the <store> scheme and the Podfile mapping. Run
# `pod install` (in ios/) afterwards. Safe to run again.
require 'fileutils'
require 'xcodeproj'

store, bundle_id, display_name, icon = ARGV
icon ||= 'AppIcon'
unless store && bundle_id && display_name && store.match?(/\A[a-z][a-z0-9_]*\z/)
  abort 'usage: add_store_flavor.rb <store: lowercase> <bundle id> "<Display Name>" [AppIcon set]'
end

ios = File.expand_path('..', __dir__)
flutter_dir = File.join(ios, 'Flutter')
FileUtils.mkdir_p(File.join(flutter_dir, 'stores'))

File.write(File.join(flutter_dir, 'stores', "#{store}.xcconfig"), <<~XC)
  // Store "#{store}": identity of its iOS app. Generated by ios/scripts/add_store_flavor.rb.
  PRODUCT_BUNDLE_IDENTIFIER = #{bundle_id}
  APP_DISPLAY_NAME = #{display_name}
  ASSETCATALOG_COMPILER_APPICON_NAME = #{icon}
XC

# Flavor configuration => [Flutter base, CocoaPods mode]
bases = { 'Debug' => 'debug', 'Release' => 'release', 'Profile' => 'release' }

project_path = File.join(ios, 'Runner.xcodeproj')
project = Xcodeproj::Project.open(project_path)
flutter_group = project.main_group.find_subpath('Flutter', false)
runner = project.targets.find { |t| t.name == 'Runner' }

bases.each_key do |base|
  name = "#{base}-#{store}"
  file_name = "#{name}.xcconfig"
  File.write(File.join(flutter_dir, file_name), <<~XC)
    #include? "Pods/Target Support Files/Pods-Runner/Pods-Runner.#{name.downcase}.xcconfig"
    #include "Generated.xcconfig"
    #include "stores/#{store}.xcconfig"
  XC
  # Same shape as the existing Debug/Release.xcconfig references.
  ref = flutter_group.files.find { |f| f.path == "Flutter/#{file_name}" } ||
        flutter_group.new_reference("Flutter/#{file_name}").tap { |r| r.name = file_name }

  # Project level and every target: copy the base configuration's settings.
  ([project] + project.targets).each do |owner|
    list = owner.build_configuration_list
    source = list[base]
    next unless source
    config = list[name] || begin
      c = project.new(Xcodeproj::Project::Object::XCBuildConfiguration)
      c.name = name
      list.build_configurations << c
      c
    end
    config.build_settings = Marshal.load(Marshal.dump(source.build_settings))
    config.base_configuration_reference =
      owner.equal?(runner) ? ref : source.base_configuration_reference
  end
end

# The store identity now comes from the xcconfig, so the target must not pin it.
runner.build_configurations.each do |c|
  c.build_settings.delete('PRODUCT_BUNDLE_IDENTIFIER')
  c.build_settings.delete('ASSETCATALOG_COMPILER_APPICON_NAME')
end
project.save

# Scheme <store>: the Runner scheme pointed at this store's configurations.
schemes = File.join(project_path, 'xcshareddata', 'xcschemes')
scheme = File.read(File.join(schemes, 'Runner.xcscheme'))
bases.each_key do |base|
  scheme = scheme.gsub(/buildConfiguration = "#{base}"/, %(buildConfiguration = "#{base}-#{store}"))
end
File.write(File.join(schemes, "#{store}.xcscheme"), scheme)

# Podfile: CocoaPods needs to know each configuration's mode.
podfile_path = File.join(ios, 'Podfile')
podfile = File.read(podfile_path)
bases.each do |base, mode|
  line = "  '#{base}-#{store}' => :#{mode},"
  next if podfile.include?(line)
  podfile = podfile.sub("project 'Runner', {\n", "project 'Runner', {\n#{line}\n")
end
File.write(podfile_path, podfile)

puts "iOS flavor '#{store}' ready (#{bundle_id}, \"#{display_name}\"). Now run: cd ios && pod install"
