#!/usr/bin/env sh
# Builds and starts a client's own website and admin from branch client/<slug>,
# and sends the given hosts to them (every other host keeps the shared ones).
#   ./scripts/deploy-client.sh <slug> <host> [<host> ...]
# Hosts with "-admin." or starting with "admin." go to the admin; the rest to
# the website. Use the same hosts as the store's domains in the holder.
# Run again after merging changes into the branch to redeploy it.
set -eu
cd "$(dirname "$0")/.."
slug=${1:-}
[ -n "$slug" ] && [ $# -ge 2 ] || { echo "usage: $0 <slug> <host> [<host> ...]" >&2; exit 2; }
case "$slug" in *[!a-z0-9-]*) echo "slug: lowercase letters, digits and - only" >&2; exit 2;; esac
shift
branch="client/$slug"
repo=$(git rev-parse --show-toplevel)
tree=".worktrees/$slug"

git -C "$repo" rev-parse --verify --quiet "$branch" >/dev/null \
  || git -C "$repo" fetch origin "$branch:$branch" \
  || { echo "branch $branch not found" >&2; exit 1; }
if [ -d "$tree" ]; then
  git -C "$tree" checkout -q "$branch"
  git -C "$tree" pull -q --ff-only 2>/dev/null || true
else
  git -C "$repo" worktree add -q "deploy/$tree" "$branch"
fi

cat > "clients/$slug.yml" <<YML
# Generated by scripts/deploy-client.sh for $slug (branch $branch).
services:
  web-$slug:
    build: ./$tree/web
    restart: unless-stopped
    depends_on: [api]
  admin-$slug:
    build: ./$tree/admin
    restart: unless-stopped
    depends_on: [api]
YML

map="proxy/clients/$slug.map"
echo "# Generated by scripts/deploy-client.sh for $slug." > "$map"
for host in "$@"; do
  case "$host" in
    *-admin.*|admin.*) echo "$host admin-$slug:80;" >> "$map" ;;
    *) echo "$host web-$slug:80;" >> "$map" ;;
  esac
done

./scripts/compose.sh up -d --build "web-$slug" "admin-$slug"
./scripts/compose.sh exec proxy nginx -t
./scripts/compose.sh exec proxy nginx -s reload
echo "Deployed $slug from $branch for: $*"
